#!/usr/bin/env python3
"""
make_scaler_header.py

Creates a C header that contains StandardScaler params AND the normalized data
for every row in the CSV as a static 2D array, using fixed (non-exponential)
decimal notation for numeric literals.

Usage example (Windows CMD):
python "D:\Code\Masters\Thesis\CNN_1D\modeling_and_evaluation\make_scaler_header.py" ^
  --input "D:\Code\Masters\Thesis\CNN_1D\dataset\LG_HG2_processed\n20degC\611_Mixed4_processed.csv" ^
  --out "D:\Code\Masters\Thesis\CNN_1D\modeling_and_evaluation\scaler_with_rows.h" ^
  --ctype float --no_suffix

Options:
  --precision N     override decimal places (default: 10 for float, 16 for double)
  --no_suffix       do not append trailing 'f' to float literals
  --inplace         also generate in-place normalizer (optional)
  --features ...    explicit feature list (optional)
  --exclude ...     exclude columns (optional)
  --fit_csv PATH    CSV to fit scaler on (default: same as input)
"""

import argparse
from pathlib import Path
import re
import sys

import numpy as np
import pandas as pd
from sklearn.preprocessing import StandardScaler

def parse_args():
    p = argparse.ArgumentParser(description="Create C header with scaler params & normalized rows (fixed decimal format).")
    p.add_argument("--input", "-i", required=True, help="Input CSV path")
    p.add_argument("--fit_csv", "-f", help="CSV to fit scaler on (default: same as input)")
    p.add_argument("--out", "-o", required=True, help="Output header path")
    p.add_argument("--features", nargs="+", help="Explicit list of feature columns to use")
    p.add_argument("--exclude", nargs="+", help="Columns to exclude when auto-detecting numeric columns")
    p.add_argument("--ctype", choices=["float", "double"], default="float", help="C numeric type in header")
    p.add_argument("--precision", type=int, default=None, help="Decimals after point (overrides default)")
    p.add_argument("--no_suffix", action="store_true", help="Do not append 'f' to float literals")
    p.add_argument("--inplace", action="store_true", help="Also generate in-place normalizer")
    return p.parse_args()

def infer_numeric_columns(df: pd.DataFrame, exclude=None):
    cols = df.select_dtypes(include=[np.number]).columns.tolist()
    if exclude:
        cols = [c for c in cols if c not in set(exclude)]
    return cols

def sanitize_string_for_c_literal(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')

def write_header(out_path: Path, feature_names, means, scales, normalized_matrix,
                 ctype="float", precision=None, no_suffix=False, inplace=False, source_csv=None):
    rows, cols = normalized_matrix.shape
    # default precision
    if precision is None:
        precision = 10 if ctype == "float" else 16

    # format functions (fixed decimal, no exponent)
    fmt_fixed = "{{:.{}f}}".format(precision)

    suffix = "" if (no_suffix or ctype == "double") else "f"
    cdecl = "float" if ctype == "float" else "double"

    header_guard = re.sub(r'[^0-9A-Za-z]', '_', out_path.stem).upper() + "_H"
    lines = []
    lines.append("/* Auto-generated StandardScaler parameters header */")
    if source_csv:
        lines.append(f"/* Source CSV: {source_csv} */")
    lines.append("/* Generated by make_scaler_header_with_rows_fixed.py */")
    lines.append("")
    lines.append(f"#ifndef {header_guard}")
    lines.append(f"#define {header_guard}")
    lines.append("")
    lines.append("#include <stddef.h>")
    lines.append("")
    lines.append(f"#define FEATURE_COUNT {cols}")
    lines.append(f"#define ROW_COUNT {rows}")
    lines.append("")
    # feature names
    lines.append("static const char* FEATURE_NAMES[FEATURE_COUNT] = {")
    for n in feature_names:
        lines.append(f'    "{sanitize_string_for_c_literal(n)}",')
    lines.append("};")
    lines.append("")
    # means
    lines.append(f"static const {cdecl} FEATURE_MEAN[FEATURE_COUNT] = {{")
    for v in means:
        lit = fmt_fixed.format(float(v)) + suffix
        lines.append(f"    {lit},")
    lines.append("};")
    lines.append("")
    # scales
    lines.append(f"static const {cdecl} FEATURE_SCALE[FEATURE_COUNT] = {{")
    for v in scales:
        lit = fmt_fixed.format(float(v)) + suffix
        lines.append(f"    {lit},")
    lines.append("};")
    lines.append("")
    # normalized 2D array (row-major)
    lines.append(f"static const {cdecl} NORMALIZED_DATA[ROW_COUNT][FEATURE_COUNT] = {{")
    for r in range(rows):
        row_vals = ", ".join((fmt_fixed.format(float(x)) + suffix) for x in normalized_matrix[r, :])
        lines.append("    { " + row_vals + " },")
    lines.append("};")
    lines.append("")
    # helper functions
    lines.append("/* Copy row 'r' into buffer 'out' (out must have space for FEATURE_COUNT elements). */")
    lines.append(f"static inline void get_normalized_row(size_t r, {cdecl} *out, size_t n) {{")
    lines.append("    if (n < FEATURE_COUNT) return;")
    lines.append("    if (r >= (size_t)ROW_COUNT) return;")
    lines.append("    for (size_t i = 0; i < (size_t)FEATURE_COUNT; ++i) out[i] = NORMALIZED_DATA[r][i];")
    lines.append("}")
    lines.append("")
    if inplace:
        lines.append("/* In-place normalization helper: modifies the buffer `buf` of length FEATURE_COUNT. */")
        lines.append(f"static inline void normalize_inplace({cdecl} *buf, size_t n) {{")
        lines.append("    if (n < FEATURE_COUNT) return;")
        lines.append("    for (size_t i = 0; i < (size_t)FEATURE_COUNT; ++i)")
        lines.append("        buf[i] = (buf[i] - FEATURE_MEAN[i]) / FEATURE_SCALE[i];")
        lines.append("}")
        lines.append("")
    lines.append(f"#endif /* {header_guard} */")
    out_path.write_text("\n".join(lines))
    return out_path

def parse_normalized_from_header(text: str):
    """
    Extract the NORMALIZED_DATA block as a list of lists of floats.
    Works with fixed decimal literals as well as 'f' suffix.
    """
    m = re.search(r"NORMALIZED_DATA\s*\[\s*ROW_COUNT\s*\]\s*\[\s*FEATURE_COUNT\s*\]\s*=\s*\{(.*?)\};", text, re.S)
    if not m:
        raise ValueError("Cannot find NORMALIZED_DATA block in header.")
    block = m.group(1)
    rows = re.findall(r"\{([^}]*)\}", block, re.S)
    parsed = []
    for row in rows:
        nums = re.findall(r"([+-]?\d+(?:\.\d*)?(?:[eE][+-]?\d+)?)[fF]?", row)
        parsed.append([float(x) for x in nums])
    return np.array(parsed, dtype=float)

def main():
    args = parse_args()
    input_path = Path(args.input)
    if not input_path.exists():
        print("Input CSV not found:", input_path)
        sys.exit(2)

    fit_path = Path(args.fit_csv) if args.fit_csv else input_path
    if not fit_path.exists():
        print("Fit CSV not found:", fit_path)
        sys.exit(3)

    # Load CSVs
    df_input = pd.read_csv(input_path, low_memory=False)
    df_fit = pd.read_csv(fit_path, low_memory=False)

    # Determine feature columns
    if args.features:
        feature_cols = args.features
        missing = [c for c in feature_cols if c not in df_fit.columns]
        if missing:
            raise ValueError("Specified feature columns not found in fit CSV: " + ", ".join(missing))
    else:
        feature_cols = infer_numeric_columns(df_fit, exclude=args.exclude)
        if not feature_cols:
            raise ValueError("No numeric columns found. Provide --features.")

    # Fit scaler
    scaler = StandardScaler()
    fit_data = df_fit[feature_cols].astype(float).values
    scaler.fit(fit_data)

    # Transform full input CSV (all rows)
    input_data = df_input[feature_cols].astype(float).values
    normalized = scaler.transform(input_data)  # shape: (n_rows, n_features)

    # Prepare header
    out_path = Path(args.out)
    write_header(out_path, feature_cols, scaler.mean_, scaler.scale_, normalized,
                 ctype=args.ctype, precision=args.precision, no_suffix=args.no_suffix,
                 inplace=args.inplace, source_csv=input_path.name)

    print(f"Wrote header: {out_path}")
    print(f"Feature count: {len(feature_cols)}, Rows: {normalized.shape[0]}")

    # Verification: read header and parse NORMALIZED_DATA and compare with computed normalized
    header_text = out_path.read_text()
    parsed = parse_normalized_from_header(header_text)

    if parsed.shape != normalized.shape:
        print("Verification FAILED: shapes differ between computed normalized data and header-parsed data.")
        print("Computed shape:", normalized.shape, "Parsed shape:", parsed.shape)
        sys.exit(4)

    atol = 1e-6 if args.ctype == "double" else 1e-5
    rtol = 1e-6

    diffs = np.abs(parsed - normalized)
    max_diff = float(np.max(diffs))
    max_idx = np.unravel_index(int(np.argmax(diffs)), diffs.shape)
    if not np.allclose(parsed, normalized, rtol=rtol, atol=atol):
        print("Verification FAILED: numeric mismatch between header data and computed normalized data.")
        print(f"Max absolute difference: {max_diff} at row {max_idx[0]}, col {max_idx[1]}")
        r, c = max_idx
        print("Computed value:", normalized[r, c])
        print("Parsed    value:", parsed[r, c])
        sys.exit(5)
    else:
        print("Verification PASSED: header NORMALIZED_DATA matches computed normalized data (within tolerance).")
        print(f"Maximum absolute difference: {max_diff:.3e}")

    # also dump a CSV copy of normalized data beside header for convenience
    normalized_csv = out_path.with_suffix(".normalized.csv")
    pd.DataFrame(normalized, columns=feature_cols).to_csv(normalized_csv, index=False)
    print("Saved normalized CSV for inspection:", normalized_csv)

if __name__ == "__main__":
    main()
